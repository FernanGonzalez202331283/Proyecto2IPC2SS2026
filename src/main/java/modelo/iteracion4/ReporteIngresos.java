public class ReporteIngresos {
    private int cantidadPagos;
    private double totalIngresos;
    private double totalInscripciones;
    private double totalColegiaturas;
    private double totalActividades;
    
    public ReporteIngresos(){
        
    }

    public int getCantidadPagos() {
        return cantidadPagos;
    }

    public void setCantidadPagos(int cantidadPagos) {
        this.cantidadPagos = cantidadPagos;
    }

    public double getTotalIngresos() {
        return totalIngresos;
    }

    public void setTotalIngresos(double totalIngresos) {
        this.totalIngresos = totalIngresos;
    }

    public double getTotalInscripciones() {
        return totalInscripciones;
    }

    public void setTotalInscripciones(double totalInscripciones) {
        this.totalInscripciones = totalInscripciones;
    }

    public double getTotalColegiaturas() {
        return totalColegiaturas;
    }

    public void setTotalColegiaturas(double totalColegiaturas) {
        this.totalColegiaturas = totalColegiaturas;
    }

    public double getTotalActividades() {
        return totalActividades;
    }

    public void setTotalActividades(double totalActividades) {
        this.totalActividades = totalActividades;
    }
    
    
}
