package modelo.seccion;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;

/**
 *
 * @author fernan
 */
@JsonIgnoreProperties(ignoreUnknown = true)
public class SeccionRequest {
    private int idGrado;
    private int idAnioLectivo;
    private String nombre;
    private int capacidad;
    private Boolean estado;
    
    public SeccionRequest() {}

    public int getIdGrado() {
        return idGrado;
    }

    public void setIdGrado(int idGrado) {
        this.idGrado = idGrado;
    }

    public int getIdAnioLectivo() {
        return idAnioLectivo;
    }

    public void setIdAnioLectivo(int idAnioLectivo) {
        this.idAnioLectivo = idAnioLectivo;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public int getCapacidad() {
        return capacidad;
    }

    public void setCapacidad(int capacidad) {
        this.capacidad = capacidad;
    }

    public Boolean getEstado() {
        return estado;
    }

    public void setEstado(Boolean estado) {
        this.estado = estado;
    }
    
    
}
